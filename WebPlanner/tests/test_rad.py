"""Known-answer tests: WS4 RAD parser, storm numbers, tripwire, leash (brief WS4; SPEC §9 RAD; F14).

Two kinds of test:
1. SYNTHETIC (CI): a CDAS-format text listing built here with analytic answers. Baseline week
   flat at 200 uGy/day (with a 190/200/210 wobble, median 200); in the storm window a
   triangular pulse 200 -> 8200 over 12 samples and back over 24 samples at 18-min cadence,
   so peak = 8.2 mGy/day and excess = 0.5 x 8000 uGy/day x (36 x 18 min = 0.45 day) = 1.8 mGy;
   one single-sample spike (700 > 3 x 200) that must not trip; one fill value (-1e31).
   Values are invented test inputs, never shipped.
2. REAL (local, skipped where data/ is absent): the cached CDAS RAD L2 storm listing
   (python -m pipeline.conditions.fetch rad). Expected ranges from SPEC F14 / brief WS4 /
   config rad.expected: peak 8.1-8.4 mGy/day, excess 1.7-1.9 mGy; tripwire before the peak.
Leash KAT (brief WS4): tau = 60 * D_allow / Ddot at 0.35 mGy/h and 0.5 mGy -> ~85 min (85.7).
"""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta

import pytest

from pipeline.conditions import rad, tripwire
from pipeline.conditions.config import RAW, load_conditions

CFG = load_conditions()
COMP = CFG["rad"]["dose_component"]
BUILD_UTC = datetime(2026, 11, 14, 12, tzinfo=UTC)
CAD = timedelta(minutes=18)
T0 = datetime.fromisoformat(CFG["rad"]["storm_window_utc"][0].replace("Z", "+00:00"))
BASE = 200.0
ONSET_K, RISE, FALL, PEAK = 90, 12, 24, 8200.0
SPIKE_K = 40
FILL_K = -100


def _value(k: int) -> float:
    if k < 0:
        return -1.0e31 if k == FILL_K else (190.0, 200.0, 210.0)[k % 3]
    if k == SPIKE_K:
        return 700.0
    if ONSET_K < k <= ONSET_K + RISE:
        return BASE + (PEAK - BASE) * (k - ONSET_K) / RISE
    if ONSET_K + RISE < k <= ONSET_K + RISE + FALL:
        return PEAK - (PEAK - BASE) * (k - ONSET_K - RISE) / FALL
    return BASE


def cdas_text(k0: int, k1: int, value=_value, units="uGray/day_(good_Q)") -> str:
    """A CDAS REST format=text listing (EPOCH + 3 dose columns), tags = sample START."""
    lines = ["#  SYNTHETIC test listing (CDAS format), NOT RAD data",
             "EPOCH  TOTAL_DOSE_B  RTG_CORRECTED_DOSE_B  TOTAL_DOSE_E",
             f"dd-mm-yyyy hh:mm:ss.mil.mic.nan  {units}  {units}  {units}"]
    for k in range(k0, k1):
        t = T0 + k * CAD - CAD / 2  # sample k's MIDPOINT is T0 + k*CAD
        v = value(k)
        lines.append(f"{t:%d-%m-%Y %H:%M:%S}.000.000.000  1.0  1.0  {v:.3f}")
    lines.append("# Generated by a test")
    return "\n".join(lines) + "\n"


def storm_text() -> str:
    return cdas_text(-7 * 80, 4 * 80)  # 7 baseline days + 4 storm days at 80 samples/day


@pytest.fixture
def series():
    return rad.parse_cdas_text(storm_text(), COMP, time_tag="start")


@pytest.fixture
def numbers(series):
    return rad.storm_numbers(series, CFG)


# ------------------------------------------------------------------ units and parser


@pytest.mark.parametrize("units,factor", [
    ("uGray/day_(good_Q)", 1.0), ("uGy/day", 1.0), ("µGy/day", 1.0), ("mGy/day", 1000.0),
    ("uGy/h", 24.0), ("mGy/h", 24000.0)])
def test_units_to_ugy_day(units, factor):
    assert rad.to_ugy_day_factor(units) == pytest.approx(factor)


@pytest.mark.parametrize("units", ["counts", "", None, "Gy", "rad/day"])
def test_unknown_units_refused(units):
    with pytest.raises(rad.UnitsError):
        rad.to_ugy_day_factor(units)


def test_parse_cdas(series):
    assert len(series.mid) == 11 * 80
    assert series.median_spacing == CAD
    assert series.units_in == "uGray/day_(good_Q)"
    assert series.component == COMP
    assert sum(v is None for v in series.value) == 1  # the fill
    assert series.mid[7 * 80] == T0  # start tag + half a sample = midpoint


def test_parse_converts_units():
    s = rad.parse_cdas_text(cdas_text(0, 5, lambda k: 0.5, "mGray/day"), COMP, "start")
    assert s.value[0] == pytest.approx(500.0)


def test_time_tag_shifts_midpoints():
    a = rad.parse_cdas_text(storm_text(), COMP, "start")
    c = rad.parse_cdas_text(storm_text(), COMP, "center")
    assert a.mid[0] - c.mid[0] == CAD / 2
    with pytest.raises(ValueError):
        rad.parse_cdas_text(storm_text(), COMP, "sometime")


def test_missing_component_refused():
    with pytest.raises(KeyError):
        rad.parse_cdas_text(storm_text(), "NOT_A_COLUMN", "start")


def test_not_cdas_refused():
    with pytest.raises(ValueError):
        rad.parse_cdas_text("hello\nworld\n", COMP, "start")


def test_sample_durations_capped_at_median():
    tags = [T0 + timedelta(minutes=m) for m in (0, 16, 32, 40, 48, 64, 100)]
    med, durs = rad.sample_durations(tags)
    assert med == timedelta(minutes=16)
    assert [d / timedelta(minutes=1) for d in durs] == [16, 16, 8, 8, 16, 16, 16]


# ------------------------------------------------------------------ storm numbers (synthetic)


def test_baseline_is_median_of_week(numbers):
    assert numbers["baseline_uGy_day"] == pytest.approx(BASE)


def test_peak(numbers):
    assert numbers["peak_uGy_day"] == pytest.approx(PEAK)
    assert numbers["peak_utc"] == T0 + (ONSET_K + RISE) * CAD


def test_excess_analytic(numbers):
    assert numbers["excess_mGy"] == pytest.approx(1.8, rel=1e-9)
    assert numbers["dose_equivalent_mSv"] == pytest.approx(1.8 * 1.0)  # Q = 1 for the SEP


def test_onset_and_end(numbers):
    assert numbers["onset_utc"] == T0 + ONSET_K * CAD
    assert numbers["end_utc"] == T0 + (ONSET_K + RISE + FALL) * CAD


def test_tripwire_two_consecutive_not_spike(numbers):
    # k = ONSET+1 is the first sample > 600; the second at ONSET+2 fires at its end
    assert numbers["tripwire_utc"] == T0 + (ONSET_K + 2) * CAD + CAD / 2
    assert numbers["tripwire_utc"] < numbers["peak_utc"]  # fires before the peak
    assert numbers["tripwire_utc"] > T0 + SPIKE_K * CAD  # the lone spike did not trip


def test_tripwire_fill_breaks_run():
    mid = [T0 + i * CAD for i in range(4)]
    d = [CAD] * 4
    assert tripwire.tripwire_time(mid, [700, None, 700, 100], d, 200, 3.0, 2) is None
    assert tripwire.tripwire_time(mid, [700, 700, 100, 100], d, 200, 3.0, 2) == mid[1] + CAD / 2
    assert tripwire.tripwire_time(mid, [700, 700, 100, 100], d, None, 3.0, 2) is None


def test_q_never_three():
    bad = json.loads(json.dumps(CFG))
    bad["rad"]["q_sep"] = 3.0
    with pytest.raises(ValueError):
        rad.storm_numbers(rad.parse_cdas_text(storm_text(), COMP, "start"), bad)


def test_unbounded_event_excess_unknown():
    # rate still far above baseline at the window end, data stops early: excess unknown
    s = rad.parse_cdas_text(cdas_text(-7 * 80, 100, lambda k: 5000.0 if k > 50 else _value(k)),
                            COMP, "start")
    n = rad.storm_numbers(s, CFG)
    assert n["excess_mGy"] is None and n["peak_uGy_day"] == pytest.approx(5000.0)


