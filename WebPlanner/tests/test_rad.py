# ------------------------------------------------------------------ rad.json


def test_rad_json_contract_and_units(series, tmp_path):
    latest = rad.parse_cdas_text(cdas_text(0, 20), COMP, "start")
    obj = rad.build_rad(series, latest, CFG, BUILD_UTC)  # validates against contracts
    assert obj["storm_2024"]["peak_uGy_day"] == pytest.approx(PEAK)
    assert obj["storm_2024"]["excess_mGy"] == pytest.approx(1.8)
    assert obj["leash"]["D_allow_mGy"] == CFG["leash"]["d_allow_mgy"]
    assert obj["leash"]["tau_min_at_peak"] == pytest.approx(
        60 * 0.5 / (PEAK / 1000 / 24), abs=0.05)
    rows = obj["leash"]["table"]
    lo, hi = CFG["leash"]["d_allow_range_mgy"]
    assert rows[0]["D_allow_mGy"] == lo and rows[-1]["D_allow_mGy"] == hi
    assert obj["latest"]["lag_days"] > 0
    # every numeric value names its units (SPEC §9 RAD): units in each numeric key or a sibling
    for path, key in rad.iter_numeric_keys(obj):
        assert rad.units_of(key) is not None, path
    # write + manifest (pytest: fragments go to a temp dir)
    p = rad.write_rad(obj, tmp_path / "rad.json", fragment_dir=tmp_path / "m")
    assert json.loads(p.read_text())["storm_2024"]["peak_uGy_day"] == pytest.approx(PEAK)
    frag = json.loads(next((tmp_path / "m").glob("*.json")).read_text())
    assert frag["rad.storm_2024.excess_mGy"]["units"] == "mGy"


