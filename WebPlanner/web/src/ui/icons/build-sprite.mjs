#!/usr/bin/env node
// Builds web/src/ui/icons/sprite.svg and names.gen.ts from lucide/*.svg (Lucide, ISC; copied
// unchanged from lucide-static) and custom/*.svg (original HOMELINE marks). DESIGN §3.5, D73.
//
//   node src/ui/icons/build-sprite.mjs           write sprite.svg + names.gen.ts
//   node src/ui/icons/build-sprite.mjs --check   exit 1 if either file is stale
//
// Every symbol is <symbol id="i-NAME" viewBox="0 0 24 24"> with one <g> that sets
// fill="none" stroke="currentColor" and the DESIGN stroke width (1.5), so icons take the text
// colour of their parent and no colour literal lives in the sprite.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SETS = ['lucide', 'custom']
const SPRITE = join(here, 'sprite.svg')
const NAMES = join(here, 'names.gen.ts')
// DESIGN §3.5: "one outline set at 1.5 px stroke". Lucide ships 2; the sprite overrides it.
const STROKE_WIDTH = '1.5'

function parseSvg(text, file) {
  const noComments = text.replace(/<!--[\s\S]*?-->/g, '')
  const open = noComments.match(/<svg\b([^>]*)>/)
  const close = noComments.lastIndexOf('</svg>')
  if (!open || close < 0) throw new Error(`${file}: not an <svg> document`)
  const attrs = open[1]
  const viewBox = attrs.match(/viewBox="([^"]+)"/)?.[1]
  if (viewBox !== '0 0 24 24') throw new Error(`${file}: viewBox must be "0 0 24 24", got ${viewBox}`)
  const body = noComments.slice(open.index + open[0].length, close)
  const inner = body
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join('')
  if (/#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(/.test(inner)) throw new Error(`${file}: colour literal inside an icon; use currentColor`)
  if (/\b(fill|stroke)="(?!none|currentColor)[^"]*"/.test(inner)) throw new Error(`${file}: fill/stroke must be none or currentColor`)
  return inner
}

export function buildSprite() {
  const symbols = []
  const names = []
  for (const set of SETS) {
    const dir = join(here, set)
    for (const f of readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
      const name = f.slice(0, -4)
      if (names.includes(name)) throw new Error(`icon name "${name}" exists in two sets`)
      names.push(name)
      const inner = parseSvg(readFileSync(join(dir, f), 'utf8'), `${set}/${f}`)
      symbols.push(
        `<symbol id="i-${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="${STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round">${inner}</g></symbol>`,
      )
    }
  }
  const sprite = [
    '<!-- GENERATED by web/src/ui/icons/build-sprite.mjs. Do not edit by hand. -->',
    '<!-- Lucide icons (ISC; some derived from Feather, MIT): see LICENSE-lucide.txt. Custom marks: original HOMELINE drawings. -->',
    '<svg xmlns="http://www.w3.org/2000/svg">',
    ...symbols,
    '</svg>',
    '',
  ].join('\n')
  const ts = [
    '// GENERATED by web/src/ui/icons/build-sprite.mjs. Do not edit by hand.',
    `export const ICON_NAMES = [\n${names.map((n) => `  '${n}',`).join('\n')}\n] as const`,
    '',
    'export type IconName = (typeof ICON_NAMES)[number]',
    '',
  ].join('\n')
  return { sprite, ts, names }
}

function main(argv) {
  const { sprite, ts, names } = buildSprite()
  if (argv.includes('--check')) {
    const read = (p) => {
      try {
        return readFileSync(p, 'utf8')
      } catch {
        return ''
      }
    }
    if (read(SPRITE) !== sprite || read(NAMES) !== ts) {
      console.error('icons/sprite.svg or icons/names.gen.ts is stale; run: node src/ui/icons/build-sprite.mjs')
      return 1
    }
    console.log(`sprite in sync (${names.length} icons)`)
    return 0
  }
  writeFileSync(SPRITE, sprite)
  writeFileSync(NAMES, ts)
  console.log(`wrote sprite.svg and names.gen.ts (${names.length} icons)`)
  return 0
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = main(process.argv.slice(2))
}
